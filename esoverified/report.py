"""Per-problem report cards: a datasheet a lab can read before training on a task.

For each problem: are its tests public, how many deliberately wrong programs the official
tests let through (with a witness), how the fresh suite does, whether the impossible
variant is really impossible for the reference, and (when an oracle manifest is given)
which target languages have a verified reference program.
"""

from __future__ import annotations

import json
from dataclasses import asdict
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from .audit import ProblemAudit, audit_all, summarize
from .dataset import get_problem
from .impossible import impossible_tests
from .problems import get_spec

PUBLIC_SOURCES = [
    "huggingface.co/datasets/Lossfunk/Esolang-Bench (data/*.jsonl, field test_cases)",
    "github.com/Lossfunk/EsolangBench (esolang_bench/data/*.json, field input_output_examples)",
]


def card(a: ProblemAudit, oracle_manifest: Optional[Dict[str, Dict[str, dict]]] = None) -> Dict[str, object]:
    p = get_problem(a.pid)
    ref = get_spec(a.pid).solve
    imp = impossible_tests(a.pid, 0)
    survivors = [{"mutant": m.name, "family": m.family,
                  "witness": {"input": m.witness[0], "expected": m.witness[1], "mutant_output": m.witness[2]}
                  if m.witness else None} for m in a.survivors]
    out: Dict[str, object] = {
        "pid": a.pid, "title": p.title, "difficulty": p.difficulty,
        "official_tests": len(p.tests), "official_tests_public": True,
        "mutants_valid": len(a.valid),
        "survive_official": len(a.survivors),
        "mutation_score_official": a.score("official"),
        "mutation_score_fresh": a.score("fresh"),
        "surviving_mutants": survivors,
        "impossible_variant_ok": sum(ref(i) != o for i, o in imp) == 1,
    }
    if oracle_manifest:
        out["oracles"] = {lang: {"verified_official": rows[a.pid]["verified_official"],
                                 "verified_fresh": rows[a.pid]["verified_fresh"], "max_steps": rows[a.pid]["max_steps"]}
                          for lang, rows in oracle_manifest.items() if a.pid in rows}
    return out


def build_report(out_dir: Path, pids: Sequence[str] = (), oracle_manifest: Optional[Path] = None) -> Dict[str, object]:
    audits = audit_all(pids)
    om = json.loads(oracle_manifest.read_text()) if oracle_manifest and oracle_manifest.exists() else None
    cards = [card(a, om) for a in audits]
    summary = asdict(summarize(audits))
    data = {"summary": summary, "public_test_sources": PUBLIC_SOURCES, "cards": cards}
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "report_cards.json").write_text(json.dumps(data, indent=1))
    (out_dir / "REPORT.md").write_text(render_markdown(data))
    return data


def _pct(x: Optional[float]) -> str:
    return "n/a" if x is None else f"{100 * x:.0f}%"


def render_markdown(data: Dict[str, object]) -> str:
    s = data["summary"]  # type: ignore[index]
    lines: List[str] = [
        "# EsoLang-Verified report cards", "",
        "Generated by `esoverified report`. No model was run to produce any number here.", "",
        "## Summary", "",
        f"- Deliberately wrong programs tested: **{s['mutants_valid']}** (after removing {s['equivalent']} "
        "that never differ from the reference).",
        f"- Passing all 6 official tests anyway: **{s['survivors_official']}** "
        f"({100 * s['survivors_official'] / max(1, s['mutants_valid']):.1f}%), in "
        f"**{s['problems_with_survivor']}/{s['problems']}** problems.",
        f"- Mutation score: official tests **{100 * s['score_official']:.1f}%**, fresh suite (edges + 30 random) "
        f"**{100 * s['score_fresh']:.1f}%**.",
        f"- All official tests are public: {'; '.join(data['public_test_sources'])}.",  # type: ignore[arg-type]
        "", "## By mutant family", "", "| family | wrong programs | pass official | pass fresh |", "|---|---|---|---|",
    ]
    for fam, row in sorted(s["by_family"].items()):
        lines.append(f"| {fam} | {row['valid']} | {row['survive_official']} | {row['survive_fresh']} |")
    lines += ["", "## Per problem", "",
              "| id | title | wrong programs | pass official | score official | score fresh | example survivor |",
              "|---|---|---|---|---|---|---|"]
    for c in data["cards"]:  # type: ignore[union-attr]
        ex = ""
        if c["surviving_mutants"]:
            m = c["surviving_mutants"][0]
            w = m["witness"]
            ex = f"`{m['mutant']}`"
            if w:
                ex += f" fails on `{w['input'][:24]!r}`".replace("|", "\\|")
        lines.append(f"| {c['pid']} | {c['title']} | {c['mutants_valid']} | {c['survive_official']} | "
                     f"{_pct(c['mutation_score_official'])} | {_pct(c['mutation_score_fresh'])} | {ex} |")
    return "\n".join(lines) + "\n"
